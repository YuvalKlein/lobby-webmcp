/**
 * Capture the backend's booking contract into `fixtures-openapi-booking.json`.
 *
 * The fixture that `manifest-e2e.mjs` builds its request bodies from. It is a
 * SLICE of `unitism-backend`'s `openapi.json` — a file that repo generates from
 * its own DTOs and enforces in CI (`openapi-drift-check.yml`), so it cannot
 * drift from the code that answers these endpoints.
 *
 * **Extracted, never typed out.** The two field-name defects this whole e2e
 * exists to catch (2026-09-01) were invisible because the fixture standing in
 * for the backend had been hand-written to match the schema we hoped it matched.
 * A fixture representing another service must come from that service.
 *
 *   node test/extract-booking-schema.mjs [path-to-openapi.json]
 *
 * Defaults to a sibling checkout at ../unitism-backend/openapi.json. With no
 * checkout to hand, the live spec is the same file:
 *   curl -s $API/api/docs-json > /tmp/openapi.json && node test/extract-booking-schema.mjs /tmp/openapi.json
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const SPEC_PATH = resolve(
  process.argv[2] ?? join(HERE, '../../unitism-backend/openapi.json'),
);

/** Everything the booking tools touch, and nothing else. */
const SCHEMAS = [
  'LobbyBookingOptionsDto',
  'LobbyBookingTypePublicDto',
  'LobbyAvailabilityDto',
  'LobbyBookingSlotDto',
  'LobbyBookingCreatedDto',
];
const PATHS = {
  '/lobby/agents/{slug}/booking/options': ['get'],
  '/lobby/agents/{slug}/booking/availability': ['get'],
  '/lobby/agents/{slug}/booking/bookings': ['post'],
};

const spec = JSON.parse(readFileSync(SPEC_PATH, 'utf8'));

const out = {
  _source:
    'unitism-backend openapi.json — generated by the backend from its own DTOs, ' +
    'and CI-enforced to match them (openapi-drift-check.yml). Refresh with ' +
    'test/extract-booking-schema.mjs; do not hand-edit.',
  components: { schemas: {} },
  paths: {},
};

for (const name of SCHEMAS) {
  const schema = spec.components?.schemas?.[name];
  if (!schema) throw new Error(`spec has no schema ${name} — did it get renamed?`);
  out.components.schemas[name] = schema;
}
for (const [path, methods] of Object.entries(PATHS)) {
  const node = spec.paths?.[path];
  if (!node) throw new Error(`spec has no path ${path} — did it move?`);
  out.paths[path] = {};
  for (const method of methods) {
    // Only the response contract. Request bodies, parameters, throttling and
    // prose are the backend's business; this fixture answers exactly one
    // question — what comes back.
    out.paths[path][method] = {
      operationId: node[method].operationId,
      responses: node[method].responses,
    };
  }
}

const target = join(HERE, 'fixtures-openapi-booking.json');
writeFileSync(target, JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${target} from ${SPEC_PATH}`);
for (const [name, schema] of Object.entries(out.components.schemas)) {
  console.log(`  ${name}: ${Object.keys(schema.properties ?? {}).join(', ')}`);
}
